import { chromium } from 'playwright';
import fs from 'node:fs';
const OUT = '../assets/app';
fs.mkdirSync(OUT, { recursive: true });
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1920, height: 1080 }, deviceScaleFactor: 2, reducedMotion: 'reduce' });
const p = await ctx.newPage();
await p.goto('http://localhost:4310/', { waitUntil: 'networkidle' });
await p.waitForFunction(() => document.querySelector('#hullBtn').classList.contains('ok'), null, { timeout: 30000 });
await p.addStyleTag({ content: '*{animation-duration:0s!important;transition:none!important;scroll-behavior:auto!important}' });
const shot = async (n) => { await p.waitForTimeout(500); await p.screenshot({ path: `${OUT}/${n}.png` }); console.log(n); };
await shot('s0-start');
await p.click('#inspectBtn'); await shot('s0b-inspect');
await p.click('#inspectDlg [data-close]');
await p.fill('#q', 'Who are the top 5 customers?'); await shot('s1a-typed-sealed');
await p.fill('#q', '');
await p.click('.chip.sealed >> nth=0'); await shot('s1-refused');
await p.click('.chip >> nth=0'); await p.waitForTimeout(50); await p.screenshot({ path: `${OUT}/s2a-thinking.png` });
await p.waitForFunction(() => !document.querySelector('.thinking')); await shot('s2-nrr');
await p.click('#log .link >> nth=0'); await shot('s3-payload');
await p.click('#payloadDlg [data-close]');
await p.click('#claimsBtn'); await p.waitForTimeout(50); await p.screenshot({ path: `${OUT}/s4a-claims-thinking.png` });
await p.waitForFunction(() => !document.querySelector('.thinking')); await shot('s4-claims');
await p.click('#revokeBtn'); await shot('s5-revoked');
const boxes = await p.evaluate(() => Object.fromEntries(['.founder','.investor','.egress','#seals','#files','#log','#tally','#revokeBtn','#flooded','#claimsBtn','#hullBtn','.claims','#thread'].map(s => { const r = document.querySelector(s)?.getBoundingClientRect(); return [s, r && { x: r.x, y: r.y, w: r.width, h: r.height }]; })));
fs.writeFileSync(`${OUT}/boxes.json`, JSON.stringify(boxes, null, 1));
console.log(JSON.stringify(boxes));
await b.close();
